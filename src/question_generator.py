"""
素材分析 + 分学段听力文案 / 答案生成模块（骨架）。

职责：
1. 接收待处理题图（图片路径或字节）与学段配置。
2. 调用多模态大模型识别图片内容，并依据学段教材/考纲（config/curriculum/<level>.json）
   生成符合题型的英文听力题干、中文释义、正确答案与解析。
3. 输出统一的 Question 数据结构，供 TTS 与录制模块消费。

当前阶段：仅定义数据结构与接口占位，TODO 标注真实 API 接入点。
"""
from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Union

from config.settings import LLMConfig, Settings, settings


ImageInput = Union[str, Path, bytes]  # 图片路径 或 图片二进制


@dataclass
class ChoiceOption:
    """单个选项（A 或 B）。"""

    key: str  # "A" / "B"
    image: str = ""  # 图片路径或 dataURL，传给 HTML 舞台
    description: str = ""  # 该选项的文本描述（调试/日志用）


@dataclass
class Question:
    """一道听力题的统一数据结构（题型无关的通用字段 + 题型特有字段放在 extra）。"""

    question_type: str  # 如 "image_ab_choice"
    level: str  # 学段标识，如 "primary_g4"
    level_badge: str = ""  # 舞台角标文案，如 "小学四年级"
    title: str = ""  # 舞台标题，如 "看图二选一"

    subtitle_en: str = ""  # 英文听力题干（朗读文本）
    subtitle_zh: str = ""  # 中文释义字幕
    options: List[ChoiceOption] = field(default_factory=list)
    answer: str = ""  # 正确选项 key，如 "A"
    explain: str = ""  # 答案解析（英文，可作为揭晓区补充）

    # 音频朗读文本：默认等于 subtitle_en，可由学段配置决定是否重复/拆分
    audio_text: str = ""
    read_times: int = 2

    extra: Dict[str, Any] = field(default_factory=dict)  # 题型特有字段

    def to_stage_payload(self) -> Dict[str, Any]:
        """转换为 templates/image_ab_choice.html 的 window.Stage.loadQuestion 入参。"""
        payload: Dict[str, Any] = {
            "levelBadge": self.level_badge,
            "title": self.title,
            "subtitleEn": self.subtitle_en,
            "subtitleZh": self.subtitle_zh,
            "answer": self.answer,
            "explain": self.explain,
        }
        for opt in self.options:
            if opt.key.upper() == "A":
                payload["imageA"] = opt.image
            elif opt.key.upper() == "B":
                payload["imageB"] = opt.image
        return payload


class QuestionGenerator:
    """
    素材分析 + 分学段文案生成器。

    用法：
        gen = QuestionGenerator()
        question = gen.generate(
            image_a="input/primary_g4__image_ab_choice__colors__01.png",
            image_b="input/primary_g4__image_ab_choice__colors__02.png",
            level="primary_g4",
            question_type="image_ab_choice",
        )
    """

    def __init__(self, llm_config: Optional[LLMConfig] = None, cfg: Optional[Settings] = None):
        self.cfg = cfg or settings
        self.llm = llm_config or self.cfg.llm

    # ------------------------------------------------------------------
    def generate(
        self,
        image_a: ImageInput,
        image_b: ImageInput,
        level: Optional[str] = None,
        question_type: Optional[str] = None,
    ) -> Question:
        """
        主入口：分析 A/B 两张图，生成一道听力题。

        TODO（后续接入多模态大模型）：
        1. 校验 LLM 配置（self.llm.is_configured()），未配置则抛出清晰异常。
        2. 将 image_a / image_b 编码为 base64 dataURL 或上传到模型可访问的位置。
        3. 加载学段配置：curriculum = self.cfg.load_curriculum(level)，
           把 units / core_vocabulary / core_sentences / contrast_dimensions 注入 prompt，
           约束生成内容与该学段教材对齐、难度匹配。
        4. 按 question_type 选择 prompt 模板与输出 schema（当前先实现 image_ab_choice）。
        5. 解析模型返回的 JSON，构造 Question 对象。
        6. 可选：调用 self._validate_question 做答案一致性校验。
        """
        target_level = level or self.cfg.default_level
        target_type = question_type or self.cfg.default_type

        curriculum = self.cfg.load_curriculum(target_level)

        if not self.llm.is_configured():
            raise RuntimeError(
                "LLM_API_KEY 未配置，无法生成文案。请在 .env 中填写多模态大模型配置。"
            )

        # ---- 占位：真实生成逻辑待接入 ----
        # TODO: 调用多模态 API，传入图片与 curriculum 上下文，返回结构化 JSON。
        question = Question(
            question_type=target_type,
            level=target_level,
            level_badge=curriculum.get("name", target_level),
            title="看图二选一",
            subtitle_en="TODO: generated by multimodal LLM",
            subtitle_zh="TODO: 由多模态大模型生成",
            options=[
                ChoiceOption(key="A", image=str(image_a)),
                ChoiceOption(key="B", image=str(image_b)),
            ],
            answer="",  # TODO
            explain="",
            audio_text="TODO: generated by multimodal LLM",
            read_times=int(curriculum.get("tts", {}).get("read_times", self.cfg.video.read_times)),
        )
        return question

    # ------------------------------------------------------------------
    def _validate_question(self, question: Question) -> None:
        """校验生成结果的完整性（答案必须在选项中、字幕非空等）。"""
        keys = {o.key.upper() for o in question.options}
        if question.answer and question.answer.upper() not in keys:
            raise ValueError(f"答案 {question.answer!r} 不在选项 {keys} 中")
        if not question.subtitle_en:
            raise ValueError("subtitle_en 不能为空")
